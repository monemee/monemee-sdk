// Generates test-vectors/license-signatures.json: fixed Ed25519 test vectors for the
// license signature format, shared by the JavaScript, Python and Swift test suites.
// The key pair is derived from a fixed seed and exists only for tests; it is not a
// Monemee signing key. Run: node scripts/gen-license-vectors.mjs
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PKCS8_PREFIX = Buffer.from('302e020100300506032b657004220420', 'hex');
const keyFromSeed = (hex) => crypto.createPrivateKey({ key: Buffer.concat([PKCS8_PREFIX, Buffer.from(hex, 'hex')]), format: 'der', type: 'pkcs8' });

const SEED = '4d6f6e656d65652d73646b2d746573742d766563746f72732d6b65792d303031'; // "Monemee-sdk-test-vectors-key-001"
const OTHER_SEED = '4f746865722d6b65792d6e6f742d7472757374656420627920616e792d736b64'; // unrelated key
const priv = keyFromSeed(SEED);
const other = keyFromSeed(OTHER_SEED);
const x = crypto.createPublicKey(priv).export({ format: 'jwk' }).x;

const KEY = 'MM-A7K2-9FQ3-XT8M-2B4C';
const PRODUCT_ID = 42;
const DEVICE_ID = 'd_0123456789abcdef0123456789abcdef';
const ISSUED_AT = '2026-11-20T10:00:00.000Z';

// Canonical payload: JSON with sorted keys and no whitespace, like the server.
const canonical = (obj) => JSON.stringify(Object.fromEntries(Object.entries(obj).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))));
const base = {
  v: 1, key_sha256: crypto.createHash('sha256').update(KEY).digest('hex'), product_id: PRODUCT_ID,
  device_id: DEVICE_ID, valid: true, reason: null, plan: 'pro', expires_at: null, test: false, issued_at: ISSUED_AT
};
const sign = (payload, key = priv, kid = 'test-1') => ({ payload, signature: crypto.sign(null, Buffer.from(payload), key).toString('base64url'), kid, alg: 'EdDSA' });

const valid = sign(canonical(base));
const cases = [
  { name: 'valid', expect: 'valid', signed: valid },
  { name: 'valid_with_expiry', expect: 'valid', signed: sign(canonical({ ...base, plan: 'Lifetime – Pro', expires_at: '2027-01-01T00:00:00.000Z' })) },
  { name: 'tampered_payload', expect: 'invalid', signed: { ...valid, payload: valid.payload.replace('"pro"', '"elite"') } },
  { name: 'signed_by_other_key', expect: 'invalid', signed: sign(canonical(base), other) },
  { name: 'unknown_kid', expect: 'invalid', signed: { ...valid, kid: 'mm-unknown' } },
  { name: 'truncated_signature', expect: 'invalid', signed: { ...valid, signature: valid.signature.slice(0, 40) } }
];

const out = {
  description: 'Ed25519 test vectors for Monemee license responses. Test-only key pair, not a Monemee signing key. Generated by scripts/gen-license-vectors.mjs.',
  public_key: { kid: 'test-1', kty: 'OKP', crv: 'Ed25519', x },
  license_key: KEY,
  product_id: PRODUCT_ID,
  device_id: DEVICE_ID,
  issued_at: ISSUED_AT,
  cases
};
fs.writeFileSync(path.join(root, 'test-vectors', 'license-signatures.json'), JSON.stringify(out, null, 2) + '\n');
console.log('wrote test-vectors/license-signatures.json');
